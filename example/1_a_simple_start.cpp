#include "logger.hpp"

/**
 * @file 1_a_simple_start.cpp
 * @brief mylog 基础快速上手示例
 *
 * 演示现代 C++26 无宏日志 API（基于 std::source_location 自动注入源码位置）
 * 以及传统 LOG_* 宏的双重调用方式。
 */

int main()
{
    // =========================================================================
    // 1. 现代 C++26 无宏调用（推荐：类型安全、零宏污染、自动注入文件名与行号）
    // =========================================================================
    mylog::trace("现代无宏 trace 日志: id={}", 1);
    mylog::debug("现代无宏 debug 日志: value={:.2f}", 3.14159);
    mylog::info("服务启动成功，监听端口: {}:{}", "127.0.0.1", 8080);
    mylog::warn("系统内存使用率偏高: {}%", 82.5);
    mylog::error("数据库查询超时: table={}", "user_orders");
    mylog::fatal("遇到严重故障（默认动作 NONE，不终止进程）");

    // =========================================================================
    // 2. 传统宏调用（完全兼容保留，便于老代码平滑迁移）
    // =========================================================================
    LOG_TRACE("传统宏 trace: {}", 100);
    LOG_DEBUG("传统宏 debug: {}", 200);
    LOG_INFO("传统宏 info: {}", 300);
    LOG_WARN("传统宏 warn: {}", 400);
    LOG_ERROR("传统宏 error: {}", 500);
    LOG_FATAL("传统宏 fatal: {}", 600);

    return 0;
}